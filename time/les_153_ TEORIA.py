# -----Измерение процессорного времени с time.process_time()

import time

start = time.process_time()

# Вычислительная нагрузка
total = 0
for i in range(10_000_000):
    total += i ** 0.5

end = time.process_time()

print(f"Процессорное время выполнения: {end - start} секунд")

# В отличие от time.time() или time.perf_counter(), эта функция игнорирует время ожидания, например, time.sleep():

import time

start = time.process_time()

time.sleep(2)  # Задержка — программа ничего не делает

end = time.process_time()

print(f"Процессорное время (во время сна): {end - start} секунд")

#Результат будет почти 0, потому что sleep() не загружает процессор, а process_time() считает только активную работу.

"""Измерение производительности
Измерение времени выполнения кода помогает выявить узкие места и оптимизировать программу. Помимо модуля time, для более точных замеров рекомендуется использовать модуль timeit.

Использование time.time() и time.perf_counter()
Хотя time.time() часто используется для простых замеров, time.perf_counter() обеспечивает более высокую точность и не зависит от системных часов.

import time 

# Использование time.time() 
start = time.time() 
# Операция 
end = time.time() 
print(f"Время выполнения с time.time(): {end - start} секунд") 

# Использование time.perf_counter() 
start = time.perf_counter() 
# Операция 
end = time.perf_counter() 
print(f"Время выполнения с time.perf_counter(): {end - start} секунд") 
Модуль timeit
Модуль timeit специально разработан для измерения времени выполнения небольших фрагментов кода с учетом влияния различных факторов, таких как кэширование и оптимизация.

Пример использования timeit
import timeit 

# Код для измерения 
code_to_test = """ 
total = 0 
for i in range(1000): 
    total += i
    """ 

# Замер времени выполнения 10000 раз 
execution_time = timeit.timeit(code_to_test, number=10000) 
print(f"Время выполнения: {execution_time} секунд") 
Использование timeit через консоль
Вы также можете использовать timeit напрямую из командной строки:

python -m timeit -s "import math" "math.sqrt(100)" 
Сравнение производительности различных подходов
Рассмотрим пример сравнения двух способов суммирования чисел от 0 до 999999: с использованием цикла for и встроенной функции sum.

import timeit 

# Способ 1: Цикл for 
code_for = """ 
total = 0 
for i in range(1000000): 
    total += i 
""" 

# Способ 2: Функция sum 
code_sum = """ 
total = sum(range(1000000)) 
""" 

# Замер времени 
time_for = timeit.timeit(code_for, number=100) 
time_sum = timeit.timeit(code_sum, number=100) 

print(f"Цикл for: {time_for} секунд") 
print(f"Функция sum: {time_sum} секунд") 
Результат:

Часто оказывается, что использование встроенных функций Python, таких как sum, значительно быстрее, чем ручные циклы. Это связано с тем, что встроенные функции оптимизированы на уровне C.

Практические рекомендации
Используйте time.perf_counter() или timeit для точных замеров. Они обеспечивают более высокую точность по сравнению с time.time().

Повторяйте замеры несколько раз. Это помогает сгладить случайные колебания и получить более стабильные результаты.

Избегайте измерения времени выполнения только одной операции. Лучше замерять время выполнения множества повторений и усреднять результат.

Используйте профилировщики для более глубокого анализа. Модули cProfile и profile позволяют анализировать производительность всего приложения и выявлять узкие места."""