try:
    hunters = ['Джин', 'Дон', 'Сим', 'Андрей', 'Богги', 'Кастиель']
    n = int(input())
    if hunters[n] in hunters:
        del hunters[n]
        print("Обновленный список охотников:", hunters)
except IndexError:
    print("Неверный индекс!")

    """Пользователь вводит индекс охотника, которого нужно удалить. Если индекс корректный, охотник удаляется. В противном случае выводится сообщение об ошибке: "Неверный индекс!"""