n = int(input())

x = [[i * j for j in range(1, n + 1)] for i in range(1, n + 1)]
for row in x:
    print(*row, sep=' ')


"""Пользователь вводит одно натуральное число n. Необходимо с помощью вложенных циклов вывести на экран таблицу умножения размером n×n. В этой таблице элемент в i строке и j столбце должен быть равен произведению чисел i и j. Таким образом, таблица будет содержать результаты умножения всех пар чисел от 1 до n."""